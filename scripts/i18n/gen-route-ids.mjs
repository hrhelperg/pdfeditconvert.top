/**
 * Regenerates src/lib/i18n/routeIds.ts from the English route registry.
 *
 * A canonical route id is the English path minus its leading slash ("" for
 * the home page). Emitting them as a `const` tuple gives every locale
 * manifest a real union type, so a typo in a localized route id is a
 * compile error rather than a silent 404.
 *
 * Run after adding or removing an English route:  node scripts/i18n/gen-route-ids.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync("src/lib/routes.ts", "utf8");
const re = /\{\s*path:\s*"([^"]+)"/g;
const ids = [];
let m;
while ((m = re.exec(src))) ids.push(m[1].replace(/^\//, ""));

if (ids.length === 0) throw new Error("No routes parsed from src/lib/routes.ts");
if (new Set(ids).size !== ids.length) throw new Error("Duplicate route path in src/lib/routes.ts");

const body = ids.map((id) => `  ${JSON.stringify(id)},`).join("\n");
writeFileSync(
  "src/lib/i18n/routeIds.ts",
  `/**
 * Canonical, locale-independent route identifiers.
 *
 * GENERATED by scripts/i18n/gen-route-ids.mjs — do not edit by hand.
 * A route id is the English path without its leading slash; the home page
 * is the empty string. tests/i18n/routeMap.test.ts fails if this file drifts
 * from src/lib/routes.ts.
 */

export const ROUTE_IDS = [
${body}
] as const;

export type RouteId = (typeof ROUTE_IDS)[number];

const ROUTE_ID_SET: ReadonlySet<string> = new Set(ROUTE_IDS);

export function isRouteId(value: string): value is RouteId {
  return ROUTE_ID_SET.has(value);
}

/** Route id for an English path, e.g. "/compress-pdf" -> "compress-pdf". */
export function routeIdFromEnglishPath(path: string): RouteId {
  const id = path.replace(/^\\//, "");
  if (!isRouteId(id)) throw new Error(\`Not an English route path: \${path}\`);
  return id;
}
`,
);
console.log(`Wrote src/lib/i18n/routeIds.ts with ${ids.length} route ids.`);
