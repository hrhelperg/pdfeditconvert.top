/**
 * Regenerates a locale's guide registry from the files on disk.
 *
 * The registry is a plain object of explicit imports (not a glob) so the
 * bundler can see every dependency and TypeScript can check every record.
 * Maintaining 144 import lines by hand is what this script is for.
 *
 *   node scripts/i18n/gen-guide-index.mjs pt-BR
 *   node scripts/i18n/gen-guide-index.mjs fr
 */
import { readdirSync, writeFileSync } from "node:fs";

const LOCALE_NAMES = {
  "pt-BR": "Brazilian Portuguese",
  fr: "French",
  es: "Spanish",
  de: "German",
  it: "Italian",
  ar: "Arabic",
  ru: "Russian",
  pl: "Polish",
  cs: "Czech",
  id: "Indonesian",
};

const locale = process.argv[2] ?? "pt-BR";
const localeName = LOCALE_NAMES[locale];
if (!localeName) {
  throw new Error(
    `Unknown locale "${locale}" — add it to LOCALE_NAMES in this script once its guide directory exists.`,
  );
}

const dir = `src/content/${locale}/guides`;
const constIdent = `GUIDES_${locale.toUpperCase().replace(/-/g, "_")}`;

const slugs = readdirSync(dir)
  .filter((f) => f.endsWith(".ts") && f !== "index.ts")
  .map((f) => f.replace(/\.ts$/, ""))
  .sort();

const ident = (slug) =>
  slug.replace(/[^a-z0-9]+(.)?/gi, (_, c) => (c ? c.toUpperCase() : "")).replace(/^\d/, "g$&");

const imports = slugs
  .map((s) => `import ${ident(s)} from "@/content/${locale}/guides/${s}";`)
  .join("\n");
const entries = slugs.map((s) => `  "${s}": ${ident(s)},`).join("\n");

writeFileSync(
  `${dir}/index.ts`,
  `import type { GuideContent } from "@/types/content";

${imports}

/**
 * ${localeName} guides, keyed by the **English** slug.
 *
 * GENERATED by scripts/i18n/gen-guide-index.mjs — do not edit by hand.
 *
 * The key and each record's \`slug\` are the English slug on purpose: the
 * localized URL lives in the route manifest and nowhere else, so the two
 * can never disagree. \`related\` and \`parentHub\` paths stay English too and
 * are translated at render time — see src/content/registry.ts.
 */
export const ${constIdent}: Record<string, GuideContent> = {
${entries}
};
`,
);
console.log(`Wrote ${dir}/index.ts with ${slugs.length} guides.`);
